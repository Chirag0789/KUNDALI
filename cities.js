// Each entry: [cityName, country, latitude, longitude, ianaTimezone]
// This is a DEMO dataset (92 cities). For production, replace getCityMatches()
// below with a real geocoding API call (Google Maps Geocoding API, OpenCage,
// LocationIQ, etc.) behind a server route, and resolve the IANA timezone name
// from a coordinates-to-timezone service (or the geocoder's own tz field) —
// EphemerisEngine.zonedLocalToUtc() only needs a valid IANA zone string, so no
// other code has to change.

export function getCityMatches(query, limit = 8) {
  const q = query.trim().toLowerCase();
  if (q.length < 2) return [];
  return CITIES.filter((c) => c[0].toLowerCase().includes(q)).slice(0, limit)
    .map(([name, country, lat, lon, tz]) => ({ label: `${name}, ${country}`, lat, lon, tz }));
}
